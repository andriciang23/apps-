def pick_variant(variants):
    """Smallest single pack. If that size is out, say so rather than upsell a 1kg bag."""
    singles = [v for v in variants if not re.search(r"\bx\s*\d|\+", v["title"])] or variants
    v = min(singles, key=lambda v: float(v["price"]))
    return v, (v["inventoryQuantity"] or 0) > 0


def main(src):
    nodes = {e["node"]["handle"]: e["node"] for e in json.load(open(src))["data"]["products"]["edges"]}
    out = []
    for handle, name, family, form, roast, umami, sweet, astr, caf, notes in TEAS:
        node = nodes[handle]
        variant, in_stock = pick_variant([e["node"] for e in node["variants"]["edges"]])
        slug = re.sub(r"[^a-z0-9-]+", "-", handle.encode("ascii", "ignore").decode()).strip("-")
        img_url = node["featuredMedia"]["preview"]["image"]["url"]
        img_url += ("&" if "?" in img_url else "?") + "width=480"  # Shopify CDN resize
        out.append({
            "id": slug, "handle": handle, "name": name, "family": family, "form": form,
            "roast": roast, "umami": umami, "sweetness": sweet, "astringency": astr,
            "caffeine": caf, "notes": notes,
            "size": variant["title"].split("/")[-1].strip(), "price": float(variant["price"]),
            "inStock": in_stock, "img": img_url,
            "url": f"https://hojichaya.com/products/{handle}?variant={variant['id'].split('/')[-1]}",
        })
    js = "// Generated by web/tools/build_catalogue.py. Do not edit by hand.\nwindow.HY_TEAS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
    (WEB / "teas.js").write_text(js)
    print(f"{len(out)} teas; in stock: {sum(t['inStock'] for t in out)}")

if __name__ == "__main__":
    main(sys.argv[1])
