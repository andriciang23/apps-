"""Build web/teas.js from a Shopify product export.

Usage: python3 web/tools/build_catalogue.py <products.json>
<products.json> is the search_products output (data.products.edges[].node with
variants and featuredMedia). Re-run whenever prices, stock or
tasting scores change; the page itself never calls Shopify.
"""
